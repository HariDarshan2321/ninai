"""Fresh OS account-owner verification for explicit desktop approval actions.

This is a local user-presence check, not protection against malicious software
running as the same OS user (which can modify this code or the unencrypted vault).
Only the desktop's user-initiated approval path should call ``verify_owner``.
Never expose it as an MCP tool, accept an assertion from JavaScript, or persist
the assertion as a reusable approval credential.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import secrets
import subprocess
import sys


METHOD = "macos_local_authentication"
_TIMEOUT_SECONDS = 65
_HELPER = Path(__file__).resolve().parent / "native" / "ninai-owner-auth"


class OwnerVerificationError(RuntimeError):
    """Verification did not succeed; callers must leave the approval unchanged."""


@dataclass(frozen=True)
class OwnerVerificationAssertion:
    method: str
    verified_at: str
    os_user_id: int


def _run_helper(mode: str, payload: dict | None = None) -> dict:
    if sys.platform != "darwin":
        raise OwnerVerificationError("OS owner verification is supported only on macOS.")
    if not _HELPER.is_file() or not os.access(_HELPER, os.X_OK):
        raise OwnerVerificationError("OS owner verification helper is unavailable. Install the macOS app build.")
    # The executable is bundled with Ninai; there is deliberately no environment
    # variable, request parameter, PATH lookup, or runtime compiler override.
    env = {key: value for key, value in os.environ.items() if not key.startswith("DYLD_")}
    try:
        result = subprocess.run(
            [str(_HELPER), mode],
            input=json.dumps(payload) if payload is not None else "",
            capture_output=True, text=True, timeout=_TIMEOUT_SECONDS,
            check=False, env=env,
        )
    except subprocess.TimeoutExpired as exc:
        raise OwnerVerificationError("OS owner verification timed out. Approval was not applied.") from exc
    except (OSError, UnicodeError) as exc:
        raise OwnerVerificationError("OS owner verification could not run.") from exc
    try:
        response = json.loads(result.stdout)
    except (ValueError, TypeError) as exc:
        raise OwnerVerificationError("OS owner verification returned an invalid response.") from exc
    if not isinstance(response, dict) or response.get("method") != METHOD:
        raise OwnerVerificationError("OS owner verification returned an invalid response.")
    if result.returncode != 0:
        # Never reflect helper stderr or OS-provided diagnostic strings into UI.
        reason = response.get("reason")
        messages = {
            "cancelled": "OS owner verification was cancelled. Approval was not applied.",
            "timeout": "OS owner verification timed out. Approval was not applied.",
            "unavailable": "OS owner verification is unavailable for this macOS account.",
            "failed": "OS owner verification failed. Approval was not applied.",
        }
        raise OwnerVerificationError(messages.get(reason, "OS owner verification failed. Approval was not applied."))
    return response


def check_owner_verification() -> dict:
    """Noninteractive eligibility only. This never proves owner presence."""
    try:
        result = _run_helper("--check")
        if result.get("available") is not True:
            raise OwnerVerificationError("OS owner verification is unavailable for this macOS account.")
        return {"available": True, "method": METHOD, "reason": ""}
    except OwnerVerificationError as exc:
        return {"available": False, "method": METHOD, "reason": str(exc)}


def verify_owner(reason: str) -> OwnerVerificationAssertion:
    """Prompt using macOS UI and return a fresh assertion only after success.

    ``reason`` must be generated by the desktop adapter from the exact pending
    change. Do not call this during startup, a status read, or an agent request.
    Every invocation creates a new OS context with biometric reuse disabled.
    """
    if not isinstance(reason, str) or not reason.strip() or len(reason) > 500 or any(ord(c) < 32 for c in reason):
        raise OwnerVerificationError("A short, single-line approval reason is required.")
    nonce = secrets.token_hex(32)
    result = _run_helper("--verify", {"reason": reason, "nonce": nonce})
    uid = os.getuid()
    if result.get("verified") is not True or result.get("nonce") != nonce or type(result.get("os_user_id")) is not int or result["os_user_id"] != uid:
        raise OwnerVerificationError("OS owner verification returned an invalid assertion.")
    return OwnerVerificationAssertion(
        method=METHOD,
        verified_at=datetime.now(timezone.utc).isoformat(),
        os_user_id=uid,
    )
